TINY = 1e-8


def _list_subdirs_with_manifest(root: str) -> List[str]:
    if not os.path.isdir(root):
        raise FileNotFoundError(f"Directory not found: {root}")

    names = []
    for name in sorted(os.listdir(root)):
        subdir = os.path.join(root, name)
        manifest_path = os.path.join(subdir, "manifest.csv")
        if os.path.isdir(subdir) and os.path.exists(manifest_path):
            names.append(name)
    return names


def _list_test_scenarios(case: str) -> List[str]:
    root = os.path.join("src", "scenarios", case, "test")
    return _list_subdirs_with_manifest(root)


def _read_manifest_paths(scen_dir: str, max_samples: Optional[int] = None) -> List[str]:
    """
    Read manifest.csv from one scenario directory and return full paths
    for rows whose status is ok.

    max_samples truncates the list after filtering.
    """
    manifest_path = os.path.join(scen_dir, "manifest.csv")
    if not os.path.exists(manifest_path):
        raise FileNotFoundError(f"manifest.csv not found: {manifest_path}")

    manifest = pd.read_csv(manifest_path)
    manifest = manifest[manifest["status"] == "ok"].reset_index(drop=True)

    files = manifest["file"].tolist()
    if max_samples is not None and max_samples > 0:
        files = files[: int(max_samples)]

    return [os.path.join(scen_dir, f) for f in files]


def _collect_paths(
    case: str,
    purpose: str,
    which_data: Optional[str] = None,
    max_samples: Optional[int] = None,
) -> List[str]:
    """
    this function decides which scenario files to load based on purpose

    purpose:
      - training
      - training_stressed
      - test
    which_data:
      - ignored for training
      - required for training_stressed (stress case name)
      - required for test unless using 'all'
    """
    if purpose == "training":
        scen_dir = os.path.join("src", "scenarios", case, "training")
        return _read_manifest_paths(scen_dir, max_samples=max_samples)

    if purpose == "training_stressed":
        #Note: this data gen process is time consuming, hence we generate case by case basis
        # instead of all together. Later, in augmented training, we load them all together 
        # and shuffle from a combined pool

        if not which_data:
            raise ValueError("For purpose='training_stressed', provide --which_data <stress_case_name>.")
        scen_dir = os.path.join("src", "scenarios", case, "training_stressed", str(which_data))
        return _read_manifest_paths(scen_dir, max_samples=max_samples)

    if purpose == "test":
        if which_data == "all":
            paths: List[str] = []
            for scen_name in _list_test_scenarios(case):
                scen_dir = os.path.join("src", "scenarios", case, "test", scen_name)
                paths.extend(_read_manifest_paths(scen_dir, max_samples=max_samples))
            return paths

        if not which_data:
            raise ValueError("For purpose='test', provide --which_data <test_case_name> or 'all'.")
        scen_dir = os.path.join("src", "scenarios", case, "test", str(which_data))
        return _read_manifest_paths(scen_dir, max_samples=max_samples)

    raise ValueError(f"Unsupported purpose: {purpose}")


def _limit_threads_per_process(math_threads: int = 1) -> None:
    #to prevent CPU oversubscription

    value = str(max(1, int(math_threads)))
    for name in (
        "OMP_NUM_THREADS",
        "OPENBLAS_NUM_THREADS",
        "MKL_NUM_THREADS",
        "VECLIB_MAXIMUM_THREADS",
        "NUMEXPR_NUM_THREADS",
        "BLIS_NUM_THREADS",
    ):
        os.environ[name] = value

    try:
        import torch as _torch
        _torch.set_num_threads(max(1, int(math_threads)))
        if hasattr(_torch, "set_num_interop_threads"):
            _torch.set_num_interop_threads(1)
    except Exception:
        pass


def _solve_one_path(
    path: str,
    contingency_spec: Optional[Sequence[Any]] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Build one supervised sample from one saved scenario net.

    Return DeepOPF repo-style raw pairs:
      X = PD bus load in per unit
      Y = full PG vector in per unit
    Note: saved scenarios may come from the common AC scenario-generation pipeline,
    but the label here is always regenerated by solving SC-DCOPF on the DC model.
    """
    net = util.load_net(path)
    ppc = get_dc_ppc(net)
    base_mva = float(ppc["baseMVA"])

    cont_rows = resolve_contingency_rows(
        net,
        ppc,
        contingency_spec=contingency_spec,
        scenario_path=path,
    )
    dc_case = build_dc_case(ppc, contingency_rows=cont_rows)

    pd_bus_mw = aggregate_bus_pd_from_ppc(ppc)
    sol = solve_sc_dcopf(dc_case, pd_bus_mw, x0=dc_case["base_pg"])

    if not sol["success"]:
        raise RuntimeError(f"SC-DCOPF oracle failed on {path}: {sol['message']}")

    pg_mw = np.asarray(sol["pg"], dtype=np.float32)

    pd_bus_pu = (np.asarray(pd_bus_mw, dtype=np.float32) / base_mva).astype(np.float32)
    pg_pu = (pg_mw / base_mva).astype(np.float32)

    return pd_bus_pu, pg_pu


def _get_reference_meta(
    path: str,
    contingency_spec: Optional[Sequence[Any]] = None,
) -> Dict[str, Any]:
    
    #Build metadata from one representative scenario file. Later used as 'meta'

    net = util.load_net(path)
    ppc = get_dc_ppc(net)
    base_mva = float(ppc["baseMVA"])

    cont_rows = resolve_contingency_rows(
        net,
        ppc,
        contingency_spec=contingency_spec,
        scenario_path=path,
    )
    dc_case = build_dc_case(ppc, contingency_rows=cont_rows)

    balance_idx = int(dc_case["balance_idx"])
    pred_idx = [i for i in range(dc_case["ng"]) if i != balance_idx]

    pmin_mw = np.asarray(dc_case["pmin"], dtype=np.float32)
    pmax_mw = np.asarray(dc_case["pmax"], dtype=np.float32)

    return {
        "baseMVA": base_mva,
        "nb": int(dc_case["nb"]),
        "ng": int(dc_case["ng"]),
        "balance_idx": balance_idx,
        "pred_idx": pred_idx,
        "gen_signatures": dc_case["gen_signatures"],
        "pmin_mw": pmin_mw,
        "pmax_mw": pmax_mw,
        "pmin_pu": (pmin_mw / base_mva).astype(np.float32),
        "pmax_pu": (pmax_mw / base_mva).astype(np.float32),
        "H_list": dc_case["H_list"],
        "const_list": dc_case["const_list"],
        "rate_list_mw": dc_case["rate_list"],
        "Cg": dc_case["Cg"],
        "contingency_rows": cont_rows,
        "base_pg_mw": np.asarray(dc_case["base_pg"], dtype=np.float32),
        "target_format": "full_pg_pu_raw",
        "input_format": "pd_bus_pu_raw",
    }


def _choose_num_proc(num_proc: Optional[int], n_items: int) -> int:
    if n_items <= 1:
        return 1
    if num_proc is None or int(num_proc) <= 0:
        return min(os.cpu_count() or 1, n_items)
    return max(1, min(int(num_proc), n_items))


def _load_checkpoint(
    ckpt_path: str,
) -> Tuple[Optional[Dict[str, Any]], Dict[str, Tuple[np.ndarray, np.ndarray]], List[str]]:
    """
    in case we resume datagen, start from pre-stored ckpt
    """
    if not os.path.exists(ckpt_path):
        return None, {}, []

    blob = torch.load(ckpt_path, map_location="cpu")
    meta = blob.get("meta")
    rows_by_path = blob.get("rows_by_path", {})
    failed_paths = blob.get("failed_paths", [])
    print(
        f"[resume] loaded checkpoint: {len(rows_by_path)} completed, "
        f"{len(failed_paths)} failed from {ckpt_path}",
        flush=True,
    )
    return meta, rows_by_path, failed_paths


def _save_checkpoint(
    ckpt_path: str,
    meta: Optional[Dict[str, Any]],
    rows_by_path: Dict[str, Tuple[np.ndarray, np.ndarray]],
    failed_paths: List[str],
    all_paths: Sequence[str],
    completed_count: int,
) -> None:
    payload = {
        "meta": meta,
        "rows_by_path": rows_by_path,
        "failed_paths": failed_paths,
        "all_paths": list(all_paths),
        "completed_count": int(completed_count),
    }
    torch.save(payload, ckpt_path)


def _fit_oracle_on_paths_serial(
    paths: Sequence[str],
    contingency_spec: Optional[Sequence[Any]] = None,
    ckpt_path: Optional[str] = None,
    checkpoint_every: int = 100,
    progress_every: int = 5,
    resume: bool = True,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
    """
    Serial dataset-generation loop.

    For each scenario path:
      - solve the SC-DCOPF oracle
      - store the resulting X and Y under that path key

    Final arrays preserve the original path order.
    """
    rows_by_path: Dict[str, Tuple[np.ndarray, np.ndarray]] = {}
    failed_paths: List[str] = []
    first_meta: Optional[Dict[str, Any]] = None

    if resume and ckpt_path is not None:
        first_meta, rows_by_path, failed_paths = _load_checkpoint(ckpt_path)

    total = len(paths)
    done = len(rows_by_path)

    for path in paths:
        if path in rows_by_path:
            continue

        if first_meta is None:
            first_meta = _get_reference_meta(path, contingency_spec=contingency_spec)

        try:
            x_row, y_row = _solve_one_path(path, contingency_spec=contingency_spec)
            rows_by_path[path] = (x_row, y_row)
        except Exception as e:
            failed_paths.append(path)
            print(f"[warn] failed on {path}: {e}", flush=True)
            continue

        done += 1
        if progress_every > 0 and done % progress_every == 0:
            print(f"[progress] finished {done}/{total} samples", flush=True)

        if ckpt_path is not None and checkpoint_every > 0 and done % checkpoint_every == 0:
            _save_checkpoint(ckpt_path, first_meta, rows_by_path, failed_paths, paths, done)
            print(f"[checkpoint] saved {done} completed samples to {ckpt_path}", flush=True)

    if first_meta is None and len(paths) > 0:
        first_meta = _get_reference_meta(paths[0], contingency_spec=contingency_spec)
    if first_meta is None:
        raise RuntimeError("No valid paths were found for dataset creation.")

    if ckpt_path is not None:
        _save_checkpoint(ckpt_path, first_meta, rows_by_path, failed_paths, paths, len(rows_by_path))

    ordered_paths = [p for p in paths if p in rows_by_path]
    if len(ordered_paths) == 0:
        raise RuntimeError("No successful samples were created.")

    X = np.vstack([rows_by_path[p][0] for p in ordered_paths]).astype(np.float32)
    Y = np.vstack([rows_by_path[p][1] for p in ordered_paths]).astype(np.float32)

    if failed_paths:
        print(f"[done] skipped {len(failed_paths)} failed samples", flush=True)

    return X, Y, first_meta


def _fit_oracle_on_paths_parallel(
    paths: Sequence[str],
    contingency_spec: Optional[Sequence[Any]] = None,
    num_proc: Optional[int] = None,
    math_threads_per_proc: int = 1,
    ckpt_path: Optional[str] = None,
    checkpoint_every: int = 100,
    progress_every: int = 5,
    resume: bool = True,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
    """
    Parallel dataset-generation loop using ProcessPoolExecutor.

    Each worker solves one scenario path at a time. Results are collected into
    rows_by_path so the final X and Y arrays still follow the original path order.

    Resume mode skips paths that were already completed earlier.
    """

    if len(paths) == 0:
        raise RuntimeError("No valid paths were found for dataset creation.")

    num_proc = _choose_num_proc(num_proc=num_proc, n_items=len(paths))
    if num_proc <= 1:
        return _fit_oracle_on_paths_serial(
            paths,
            contingency_spec=contingency_spec,
            ckpt_path=ckpt_path,
            checkpoint_every=checkpoint_every,
            progress_every=progress_every,
            resume=resume,
        )

    first_meta: Optional[Dict[str, Any]] = None
    rows_by_path: Dict[str, Tuple[np.ndarray, np.ndarray]] = {}
    failed_paths: List[str] = []

    if resume and ckpt_path is not None:
        first_meta, rows_by_path, failed_paths = _load_checkpoint(ckpt_path)

    remaining_paths = [p for p in paths if p not in rows_by_path]
    if len(remaining_paths) == 0:
        if first_meta is None:
            first_meta = _get_reference_meta(paths[0], contingency_spec=contingency_spec)
        ordered_paths = [p for p in paths if p in rows_by_path]
        X = np.vstack([rows_by_path[p][0] for p in ordered_paths]).astype(np.float32)
        Y = np.vstack([rows_by_path[p][1] for p in ordered_paths]).astype(np.float32)
        return X, Y, first_meta

    if first_meta is None:
        first_meta = _get_reference_meta(remaining_paths[0], contingency_spec=contingency_spec)

    ctx_name = "fork" if os.name != "nt" else "spawn"
    mp_context = mp.get_context(ctx_name)

    total = len(paths)
    done = len(rows_by_path)

    with ProcessPoolExecutor(
        max_workers=num_proc,
        mp_context=mp_context,
        initializer=_limit_threads_per_process,
        initargs=(math_threads_per_proc,),
    ) as ex:
        future_to_path = {
            ex.submit(_solve_one_path, path, contingency_spec): path
            for path in remaining_paths
        }

        for future in as_completed(future_to_path):
            path = future_to_path[future]
            try:
                x_row, y_row = future.result()
                rows_by_path[path] = (x_row, y_row)
            except Exception as e:
                failed_paths.append(path)
                print(f"[warn] failed on {path}: {e}", flush=True)
                continue

            done += 1
            if progress_every > 0 and done % progress_every == 0:
                print(f"[progress] finished {done}/{total} samples", flush=True)

            if ckpt_path is not None and checkpoint_every > 0 and done % checkpoint_every == 0:
                _save_checkpoint(ckpt_path, first_meta, rows_by_path, failed_paths, paths, done)
                print(f"[checkpoint] saved {done} completed samples to {ckpt_path}", flush=True)

    if ckpt_path is not None:
        _save_checkpoint(ckpt_path, first_meta, rows_by_path, failed_paths, paths, len(rows_by_path))

    ordered_paths = [p for p in paths if p in rows_by_path]
    if len(ordered_paths) == 0:
        raise RuntimeError("No successful samples were created.")

    X = np.vstack([rows_by_path[p][0] for p in ordered_paths]).astype(np.float32)
    Y = np.vstack([rows_by_path[p][1] for p in ordered_paths]).astype(np.float32)

    if failed_paths:
        print(f"[done] skipped {len(failed_paths)} failed samples", flush=True)

    return X, Y, first_meta


def _fit_oracle_on_paths(
    paths: Sequence[str],
    contingency_spec: Optional[Sequence[Any]] = None,
    num_proc: Optional[int] = None,
    math_threads_per_proc: int = 1,
    ckpt_path: Optional[str] = None,
    checkpoint_every: int = 100,
    progress_every: int = 5,
    resume: bool = True,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
    """
    Dispatch to the serial or parallel oracle-generation path depending on the
    chosen worker count.
    """
     
    num_proc = _choose_num_proc(num_proc=num_proc, n_items=len(paths))
    if num_proc <= 1:
        return _fit_oracle_on_paths_serial(
            paths,
            contingency_spec=contingency_spec,
            ckpt_path=ckpt_path,
            checkpoint_every=checkpoint_every,
            progress_every=progress_every,
            resume=resume,
        )

    return _fit_oracle_on_paths_parallel(
        paths,
        contingency_spec=contingency_spec,
        num_proc=num_proc,
        math_threads_per_proc=math_threads_per_proc,
        ckpt_path=ckpt_path,
        checkpoint_every=checkpoint_every,
        progress_every=progress_every,
        resume=resume,
    )


def _save_training_outputs(
    out_dir: str,
    X: np.ndarray,
    Y: np.ndarray,
    meta: Dict[str, Any],
    file_prefix: str,
    meta_name: str,
) -> None:
    os.makedirs(out_dir, exist_ok=True)

    np.save(os.path.join(out_dir, f"{file_prefix}_PD_train.npy"), X.astype(np.float32))
    np.save(os.path.join(out_dir, f"{file_prefix}_PG_train.npy"), Y.astype(np.float32))

    train_meta = dict(meta)
    train_meta["x_mu_pu"] = X.mean(axis=0).astype(np.float32)
    train_meta["x_sd_pu"] = (X.std(axis=0) + TINY).astype(np.float32)

    torch.save(train_meta, os.path.join(out_dir, meta_name))

    print(f"[done] wrote {os.path.join(out_dir, f'{file_prefix}_PD_train.npy')}", flush=True)
    print(f"[done] wrote {os.path.join(out_dir, f'{file_prefix}_PG_train.npy')}", flush=True)
    print(f"[done] wrote {os.path.join(out_dir, meta_name)}", flush=True)
    print(f"{file_prefix}_PD_train shape: {X.shape}", flush=True)
    print(f"{file_prefix}_PG_train shape: {Y.shape}", flush=True)


def _save_test_outputs(
    out_dir: str,
    which_data: str,
    X: np.ndarray,
    Y: np.ndarray,
    meta: Dict[str, Any],
) -> None:
    os.makedirs(out_dir, exist_ok=True)

    pd_name = f"PD_test_{which_data}.npy"
    pg_name = f"PG_test_{which_data}.npy"
    meta_name = f"test_meta_{which_data}.pt"

    np.save(os.path.join(out_dir, pd_name), X.astype(np.float32))
    np.save(os.path.join(out_dir, pg_name), Y.astype(np.float32))
    torch.save(meta, os.path.join(out_dir, meta_name))

    print(f"[done] wrote {os.path.join(out_dir, pd_name)}", flush=True)
    print(f"[done] wrote {os.path.join(out_dir, pg_name)}", flush=True)
    print(f"[done] wrote {os.path.join(out_dir, meta_name)}", flush=True)
    print(f"{pd_name} shape: {X.shape}", flush=True)
    print(f"{pg_name} shape: {Y.shape}", flush=True)


def build_training_dataset(
    case: str,
    out_dir: str,
    train_mode: str,
    which_data: Optional[str] = None,
    contingency_spec: Optional[Sequence[Any]] = None,
    num_proc: Optional[int] = None,
    math_threads_per_proc: int = 1,
    max_samples_train: Optional[int] = None,
    checkpoint_every: int = 100,
    progress_every: int = 5,
    resume: bool = True,
) -> None:
    """
    Build and save one training dataset.

    train_mode:
      - nominal: load src/scenarios/<case>/training
      - stressed: load src/scenarios/<case>/training_stressed/<which_data>

    For stressed mode, one stress directory is processed at a time and saved
    with a stressed_<which_data> prefix. Augmented training later merges all
    such saved stressed datasets.
    """
    if train_mode == "nominal":
        purpose = "training"
        file_prefix = "nominal"
        meta_name = "training_meta_nominal.pt"
        ckpt_name = "training_nominal_repo_style.ckpt.pt"
    elif train_mode == "stressed":
        if not which_data:
            raise ValueError("For stressed training, provide --which_data <stress_case_name>.")
        purpose = "training_stressed"
        file_prefix = f"stressed_{which_data}"
        meta_name = f"training_meta_stressed_{which_data}.pt"
        ckpt_name = f"training_stressed_{which_data}_repo_style.ckpt.pt"
    else:
        raise ValueError(f"Unsupported train_mode: {train_mode}")

    paths = _collect_paths(
        case,
        purpose=purpose,
        which_data=which_data,
        max_samples=max_samples_train,
    )

    ckpt_path = os.path.join(out_dir, ckpt_name)
    X, Y, meta = _fit_oracle_on_paths(
        paths,
        contingency_spec=contingency_spec,
        num_proc=num_proc,
        math_threads_per_proc=math_threads_per_proc,
        ckpt_path=ckpt_path,
        checkpoint_every=checkpoint_every,
        progress_every=progress_every,
        resume=resume,
    )
    _save_training_outputs(out_dir, X, Y, meta, file_prefix=file_prefix, meta_name=meta_name)


def build_test_dataset(
    case: str,
    out_dir: str,
    which_data: str,
    contingency_spec: Optional[Sequence[Any]] = None,
    num_proc: Optional[int] = None,
    math_threads_per_proc: int = 1,
    max_samples_test: Optional[int] = 500,
    checkpoint_every: int = 100,
    progress_every: int = 5,
    resume: bool = True,
) -> None:
    """
    Build and save one test dataset.

    If which_data == 'all', this concatenates samples from all test scenario
    directories, optionally truncating each one with max_samples_test.
    """
    paths = _collect_paths(
        case,
        purpose="test",
        which_data=which_data,
        max_samples=max_samples_test,
    )

    ckpt_path = os.path.join(out_dir, f"test_dataset_{which_data}_repo_style.ckpt.pt")
    X, Y, meta = _fit_oracle_on_paths(
        paths,
        contingency_spec=contingency_spec,
        num_proc=num_proc,
        math_threads_per_proc=math_threads_per_proc,
        ckpt_path=ckpt_path,
        checkpoint_every=checkpoint_every,
        progress_every=progress_every,
        resume=resume,
    )
    _save_test_outputs(out_dir, which_data, X, Y, meta)


